"""Build static/css/app.css - the ONE design-system bundle for base.html pages.

The bundle is the existing stylesheets concatenated in the exact order
base.html used to link them, so the cascade does not change. The part files
stay in static/css/ as the editable sources (the login page and a few section
pages still link two of them directly). Do not edit app.css by hand; edit a
part file and run this script again.

brand.css contains a Google Fonts @import; CSS requires @import to be the
first thing in a file, so it is hoisted to the top of the bundle.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CSS = os.path.join(HERE, '..', 'static', 'css')

ORDER = [
    'classic.css', 'pages.css', 'brand.css', 'theme.css', 'shell-light.css',
    'page-look.css', 'motion.css', 'dashboard-pro.css', 'assistant.css',
    'mg-ui.css', 'v88-polish.css', 'v89-premium.css', 'v92-theme.css',
    'v100-theme.css',
]


def main():
    imports, parts = [], []
    for name in ORDER:
        with open(os.path.join(CSS, name), encoding='utf-8') as f:
            text = f.read()
        kept = []
        for line in text.splitlines():
            if line.strip().startswith('@import'):
                imports.append(line.strip())
            else:
                kept.append(line)
        parts.append(f"\n/* ===== {name} ===== */\n" + '\n'.join(kept).strip() + '\n')
    out = ("/* MediGen AI Pro - app.css (GENERATED by scripts/build_css.py; do not edit by hand.\n"
           "   Sources, in cascade order: " + ', '.join(ORDER) + ") */\n")
    out += '\n'.join(imports) + '\n' + ''.join(parts)
    target = os.path.join(CSS, 'app.css')
    with open(target, 'w', encoding='utf-8') as f:
        f.write(out)
    print(f'wrote {target} ({len(out)} bytes) from {len(ORDER)} files, {len(imports)} @import hoisted')


if __name__ == '__main__':
    main()

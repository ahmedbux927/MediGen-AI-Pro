def _n(text):
    """Normalise a name or question for matching."""
    text = (text or "").lower()
    text = re.sub(r"[^a-z0-9]+", " ", text)
    return " " + re.sub(r"\s+", " ", text).strip() + " "


_INDEX = []
for _e in MEDICINES:
    _aliases = [_e["name"]] + list(_e.get("brands") or []) + list(_e.get("aka") or [])
    for _a in _aliases:
        _na = _n(_a)
        if len(_na.strip()) >= 4:            # ignore very short aliases (too many false hits)
            _INDEX.append((_na, _e))
_INDEX.sort(key=lambda pair: -len(pair[0]))  # longest alias wins


def find_medicine(question):
    """Return the knowledge entry a question is about, or None."""
    q = _n(question)
    for alias, entry in _INDEX:
        if alias in q:
            return entry
    return None


def format_answer(entry, shop_line=""):
    """Plain chat answer for one medicine, with the safety note."""
    out = [f"**{entry['name']}** ({entry['cat']})"]
    brands = [b for b in (entry.get("brands") or []) if " is " not in b]
    if brands:
        out.append("Common brands: " + ", ".join(brands[:4]) + ".")
    out.append("**Used for:** " + entry["uses"])
    out.append("**Common side effects:** " + entry["side"])
    out.append("**Careful:** " + entry["warn"])
    if shop_line:
        out.append(shop_line)
    out.append("_General information only - always follow the doctor's prescription and the pack leaflet._")
    return "\n".join(out)
